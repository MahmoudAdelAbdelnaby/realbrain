"""Writes Realbrain's launcher icon, themed icon and splash (V5, docs/DESIGN_V5.md §2.3) as Android
vector drawables, from the same path data the app paints: MarkPaths in lib/core/art/mark.dart.
VectorDrawable takes SVG path syntax, so the mark is copied, not redrawn.

Run from app/: python tool/brand_icons.py
(PNG icons for the web app and legacy launchers are rendered from tool/mark.svg; see that file.)
"""

import re
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
RES = APP / "android/app/src/main/res/drawable"
INK, PAPER, SAFFRON = "#FF121110", "#FFF2ECE1", "#FFF0A53A"
HEAD = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    "<!-- Generated by tool/brand_icons.py from MarkPaths (lib/core/art/mark.dart). -->\n"
)
NS = 'xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"'


def mark_paths() -> dict[str, str]:
    src = (APP / "lib/core/art/mark.dart").read_text("utf-8")
    block = src[src.index("abstract final class MarkPaths") :]
    paths = {}
    for name, body in re.findall(r"static const (\w+) =\s*((?:'[^']*'\s*)+);", block):
        paths[name] = "".join(re.findall(r"'([^']*)'", body))
    return paths


P = mark_paths()


def stroke(name: str, data: str, width: float, color: str, extra: str = "") -> str:
    return (
        f'<path android:name="{name}" android:pathData="{data}" android:strokeColor="{color}" '
        f'android:strokeWidth="{width}" android:strokeLineCap="round" android:strokeLineJoin="round"{extra}/>\n'
    )


def fill(name: str, data: str, color: str, extra: str = "") -> str:
    return f'<path android:name="{name}" android:pathData="{data}" android:fillColor="{color}"{extra}/>\n'


def mark(line: str, piece: str, seam: str | None, width: float = 4.6) -> str:
    """The mark on its 100-unit grid: piece, its seam, outline, stem and two sulci."""
    body = fill("piece", P["piece"], piece)
    if seam:
        body += stroke("seam", P["piece"], 2.6, seam)
    body += stroke("outline", P["outline"], width, line)
    body += stroke("stem", P["stem"], width, line)
    body += stroke("sulci", P["sulciSimple"], width, line)
    return body


def group(body: str, scale: float, name: str = "mark") -> str:
    # The brain spans about x 8-93, y 10-88 on its grid: centre it in the 108 dp canvas.
    t = 54 - 50 * scale
    return (
        f'<group android:name="{name}" android:translateX="{t:.2f}" android:translateY="{t - 1.5 * scale:.2f}" '
        f'android:scaleX="{scale}" android:scaleY="{scale}">\n{body}</group>\n'
    )


def vector(body: str, dp: int = 108) -> str:
    return (
        f'<vector {NS} android:width="{dp}dp" android:height="{dp}dp" '
        f'android:viewportWidth="108" android:viewportHeight="108">\n{body}</vector>\n'
    )


def splash() -> str:
    """Android 12+ splash: the outline draws itself, then the saffron piece drops into place."""
    piece = fill("piece", P["piece"], SAFFRON, ' android:fillAlpha="0"')
    seam = stroke("seam", P["piece"], 2.6, INK, ' android:strokeAlpha="0"')
    lines = (
        stroke("outline", P["outline"], 4.2, PAPER, ' android:trimPathEnd="0"')
        + stroke("stem", P["stem"], 4.2, PAPER, ' android:trimPathEnd="0"')
        + stroke("sulci", P["sulciSimple"], 4.2, PAPER, ' android:trimPathEnd="0"')
    )
    drop = f'<group android:name="drop" android:translateY="-6">\n{piece}{seam}</group>\n'
    drawable = vector(group(drop + lines, 0.5), dp=288)

    def anim(target: str, prop: str, frm: str, to: str, start: int, dur: int, kind: str = "floatType") -> str:
        return (
            f'<target android:name="{target}"><aapt:attr name="android:animation">'
            f'<objectAnimator android:propertyName="{prop}" android:valueFrom="{frm}" android:valueTo="{to}" '
            f'android:valueType="{kind}" android:startOffset="{start}" android:duration="{dur}" '
            f'android:interpolator="@android:interpolator/fast_out_slow_in"/></aapt:attr></target>\n'
        )

    targets = (
        anim("outline", "trimPathEnd", "0", "1", 0, 480)
        + anim("stem", "trimPathEnd", "0", "1", 200, 300)
        + anim("sulci", "trimPathEnd", "0", "1", 300, 300)
        + anim("piece", "fillAlpha", "0", "1", 450, 200)
        + anim("seam", "strokeAlpha", "0", "1", 450, 200)
        + anim("drop", "translateY", "-6", "0", 450, 350)
    )
    return f'<animated-vector {NS}>\n<aapt:attr name="android:drawable">\n{drawable}</aapt:attr>\n{targets}</animated-vector>\n'


def main() -> None:
    def write(name: str, text: str) -> None:
        (RES / name).write_text(HEAD + text, encoding="utf-8", newline="\n")

    write("ic_launcher_background.xml", vector(fill("ink", "M0,0 H108 V108 H0 Z", INK)))
    write("ic_launcher_foreground.xml", vector(group(mark(PAPER, SAFFRON, INK), 0.6)))
    # Themed icons: one colour; Android tints it.
    write("ic_launcher_monochrome.xml", vector(group(mark("#FF000000", "#FF000000", None), 0.6)))
    write("ic_launcher_foreground_round.xml", vector(group(mark(PAPER, SAFFRON, INK), 0.6)))
    write("splash_icon.xml", splash())
    print("wrote", ", ".join(p.name for p in sorted(RES.glob("*.xml"))))


if __name__ == "__main__":
    main()
