"""Writes the polygonal brain (docs/DESIGN_V4_PROPOSAL.md §3) as Android vector drawables.

The points and lines are the same as BrainMesh in lib/core/brain_mark.dart; change both together.
Run from app/: python tool/brain_mesh.py
"""

from pathlib import Path

OUTLINE = [(14, 52), (12, 40), (18, 29), (28, 21), (41, 16), (55, 15), (68, 18), (79, 25), (87, 35),
           (89, 47), (85, 58), (76, 64), (68, 72), (60, 80), (54, 70), (44, 66), (32, 64), (22, 60)]
INNER = [(25, 42), (36, 32), (50, 27), (63, 28), (75, 36), (40, 47), (55, 41), (68, 48), (80, 47),
         (30, 54), (47, 57), (62, 58), (74, 56)]
SPOKES = [(1, 0), (0, 0), (2, 0), (2, 1), (3, 1), (4, 1), (4, 2), (5, 2), (5, 3), (6, 3), (7, 3),
          (7, 4), (8, 4), (9, 8), (8, 8), (10, 8), (10, 12), (11, 12), (12, 11), (12, 12), (13, 11),
          (14, 11), (14, 10), (15, 10), (16, 9), (16, 10), (17, 9), (0, 9)]
MESH = [(0, 1), (1, 2), (2, 3), (3, 4), (4, 8), (0, 5), (1, 5), (2, 5), (2, 6), (3, 6), (3, 7),
        (4, 7), (6, 5), (6, 7), (7, 8), (7, 12), (8, 12), (0, 9), (5, 9), (5, 10), (9, 10), (6, 10),
        (6, 11), (10, 11), (7, 11), (11, 12)]
BIG = [2, 5, 7, 11, 9]
SIMPLE_NODES = [1, 3, 5, 7, 9, 11]
SIMPLE = [(1, 3), (1, 5), (3, 7), (5, 7), (5, 9), (5, 11), (7, 11), (9, 11)]

RES = Path(__file__).resolve().parent.parent / "android/app/src/main/res/drawable"
HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tool/brain_mesh.py: the polygonal brain (docs/DESIGN_V4_PROPOSAL.md). -->\n")
NS = 'xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"'


def lines(pairs):
    return "".join(f"M{a[0]},{a[1]} L{b[0]},{b[1]} " for a, b in pairs).strip()


def dots(points, r):
    return "".join(f"M{x - r},{y} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0 " for x, y in points).strip()


def outline():
    return "M" + " L".join(f"{x},{y}" for x, y in OUTLINE) + " Z"


def group(scale, body, size=108):
    # The brain spans y 15..80 on its 100 grid: shift 2.5 down to centre it, then centre the grid.
    offset = (size - 100 * scale) / 2
    return (f'<group android:translateX="{offset:g}" android:translateY="{offset + 2.5 * scale:g}" '
            f'android:scaleX="{scale}" android:scaleY="{scale}">\n{body}</group>\n')


def stroke(name, data, width, color, alpha=1.0):
    return (f'<path android:name="{name}" android:pathData="{data}" android:strokeColor="{color}" '
            f'android:strokeAlpha="{alpha:g}" android:strokeWidth="{width}" '
            'android:strokeLineCap="round" android:strokeLineJoin="round"/>\n')


def fill(name, data, color, alpha=1.0):
    return f'<path android:name="{name}" android:pathData="{data}" android:fillColor="{color}" android:fillAlpha="{alpha:g}"/>\n'


def simple(color):
    """Outline, six nodes and the lines between them: launcher sizes."""
    pairs = [(INNER[a], INNER[b]) for a, b in SIMPLE]
    return (stroke("outline", outline(), 4.6, color) + stroke("mesh", lines(pairs), 4.6, color)
            + fill("nodes", dots([INNER[k] for k in SIMPLE_NODES], 5.5), color))


def full(color, start_hidden=False):
    """The whole mesh: splash and the pre-Android-12 launch screen."""
    pairs = [(OUTLINE[a], INNER[b]) for a, b in SPOKES] + [(INNER[a], INNER[b]) for a, b in MESH]
    big = [INNER[k] for k in BIG]
    small = [p for p in OUTLINE + INNER if p not in big]
    hide = 0 if start_hidden else 1
    edge = stroke("outline", outline(), 1.0, color)
    if start_hidden:
        edge = edge.replace("/>", ' android:trimPathEnd="0"/>')
    return (stroke("mesh", lines(pairs), 0.7, color, 0.85 * hide)
            + edge
            + fill("nodes", dots(small, 1.1), color, hide)
            + fill("bignodes", dots(big, 2.1), color, hide))


def vector(body, size=108, dp=108):
    return (f'<vector {NS} android:width="{dp}dp" android:height="{dp}dp" '
            f'android:viewportWidth="{size}" android:viewportHeight="{size}">\n{body}</vector>\n')


HAZE = ('<path android:pathData="M0,0 H108 V108 H0 Z">\n<aapt:attr name="android:fillColor">\n'
        '<gradient android:type="radial" android:centerX="70" android:centerY="30" android:gradientRadius="100">\n'
        '<item android:offset="0" android:color="#FF2A2654"/>\n'
        '<item android:offset="0.55" android:color="#FF121530"/>\n'
        '<item android:offset="1" android:color="#FF080A14"/>\n'
        '</gradient>\n</aapt:attr>\n</path>\n')


def anim(target, prop, start, duration, frm, to):
    return (f'<target android:name="{target}">\n<aapt:attr name="android:animation">\n'
            f'<objectAnimator android:propertyName="{prop}" android:startOffset="{start}" '
            f'android:duration="{duration}" android:valueFrom="{frm}" android:valueTo="{to}" '
            'android:valueType="floatType" android:interpolator="@android:interpolator/fast_out_slow_in"/>\n'
            '</aapt:attr>\n</target>\n')


def main():
    write = lambda name, text: (RES / name).write_text(HEAD + text, encoding="utf-8", newline="\n")
    # Launcher: the mark on a navy tile with a lavender haze; inside the 66 dp safe zone.
    write("ic_launcher_background.xml", vector(HAZE))
    write("ic_launcher_foreground.xml", vector(group(0.6, simple("#FFFFFFFF"))))
    write("ic_launcher_monochrome.xml", vector(group(0.6, simple("#FF000000"))))
    # Before Android 12 the launch screen draws this at 120 dp on the ink ground.
    write("ic_launcher_foreground_round.xml", vector(group(0.9, full("#FFFFFFFF"))))
    # Android 12+ splash: the outline draws itself, then the lines and the nodes appear (800 ms).
    splash = vector(HAZE + group(0.58, full("#FFFFFFFF", start_hidden=True)), dp=288)
    write("splash_icon.xml",
          f'<animated-vector {NS}>\n<aapt:attr name="android:drawable">\n{splash}</aapt:attr>\n'
          + anim("outline", "trimPathEnd", 0, 450, 0, 1)
          + anim("mesh", "strokeAlpha", 250, 400, 0, 0.85)
          + anim("nodes", "fillAlpha", 450, 350, 0, 1)
          + anim("bignodes", "fillAlpha", 500, 300, 0, 1)
          + "</animated-vector>\n")


if __name__ == "__main__":
    main()
